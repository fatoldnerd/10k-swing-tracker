'use client';

import { useState } from 'react';
import { Card, CardContent, CardHeader, CardTitle } from '@/components/ui/card';
import { Button } from '@/components/ui/button';
import { Input } from '@/components/ui/input';
import { Label } from '@/components/ui/label';
import { Select, SelectContent, SelectItem, SelectTrigger, SelectValue } from '@/components/ui/select';
import { useWorkouts } from '@/hooks/useFirestore';
import { STRENGTH_EXERCISES, KETTLEBELL_WEIGHTS, StrengthExercise, WorkoutRound, Workout } from '@/types';
import { Plus, Save, Calculator, Clock } from 'lucide-react';
import { useRouter } from 'next/navigation';
import { format } from 'date-fns';

interface WorkoutFormData {
  date: string;
  strengthExercise: StrengthExercise;
  kettlebellWeight: number;
  totalMinutes: number;
  totalSeconds: number;
  notes: string;
  rounds: {
    roundNumber: number;
    minutes: number;
    seconds: number;
  }[];
}

export default function WorkoutLogger() {
  const router = useRouter();
  const { createWorkout } = useWorkouts();
  const [isLoading, setIsLoading] = useState(false);

  const [formData, setFormData] = useState<WorkoutFormData>({
    date: format(new Date(), 'yyyy-MM-dd'),
    strengthExercise: 'Push-ups',
    kettlebellWeight: 16,
    totalMinutes: 0,
    totalSeconds: 0,
    notes: '',
    rounds: [
      { roundNumber: 1, minutes: 0, seconds: 0 },
      { roundNumber: 2, minutes: 0, seconds: 0 },
      { roundNumber: 3, minutes: 0, seconds: 0 },
      { roundNumber: 4, minutes: 0, seconds: 0 },
    ],
  });

  const updateFormData = (field: keyof WorkoutFormData, value: string | number | StrengthExercise) => {
    setFormData(prev => ({ ...prev, [field]: value }));
  };

  const updateRoundTime = (roundIndex: number, field: 'minutes' | 'seconds', value: number) => {
    setFormData(prev => ({
      ...prev,
      rounds: prev.rounds.map((round, index) =>
        index === roundIndex ? { ...round, [field]: value } : round
      ),
    }));
  };

  const calculateTotalFromRounds = () => {
    const totalSeconds = formData.rounds.reduce((total, round) => {
      return total + (round.minutes * 60) + round.seconds;
    }, 0);
    
    const totalMinutes = Math.floor(totalSeconds / 60);
    const remainingSeconds = totalSeconds % 60;
    
    setFormData(prev => ({
      ...prev,
      totalMinutes,
      totalSeconds: remainingSeconds,
    }));
  };

  const estimateRoundTimes = () => {
    const totalWorkoutSeconds = (formData.totalMinutes * 60) + formData.totalSeconds;
    const avgRoundTime = Math.floor(totalWorkoutSeconds / 4);
    
    const estimatedRounds = formData.rounds.map((round) => ({
      ...round,
      minutes: Math.floor(avgRoundTime / 60),
      seconds: avgRoundTime % 60,
    }));
    
    setFormData(prev => ({ ...prev, rounds: estimatedRounds }));
  };

  const formatTime = (minutes: number, seconds: number): string => {
    return `${minutes}:${seconds.toString().padStart(2, '0')}`;
  };

  const validateForm = (): boolean => {
    if (!formData.date) return false;
    if (formData.totalMinutes === 0 && formData.totalSeconds === 0) return false;
    return true;
  };

  const handleSubmit = async (e: React.FormEvent) => {
    e.preventDefault();
    
    if (!validateForm()) {
      alert('Please fill in all required fields');
      return;
    }

    setIsLoading(true);
    
    try {
      const roundData: WorkoutRound[] = formData.rounds.map((round) => ({
        id: '', // Will be generated by Firestore
        workoutId: '', // Will be set by the service
        roundNumber: round.roundNumber,
        timeMinutes: round.minutes,
        timeSeconds: round.seconds,
        createdAt: new Date(), // Will be set by the service
      }));

      const workoutData: Omit<Workout, 'id' | 'createdAt' | 'updatedAt'> = {
        date: new Date(formData.date),
        strengthExercise: formData.strengthExercise,
        kettlebellWeight: formData.kettlebellWeight,
        totalTimeMinutes: formData.totalMinutes,
        totalTimeSeconds: formData.totalSeconds,
        completed: true,
        notes: formData.notes || undefined,
        rounds: roundData,
      };

      await createWorkout(workoutData);
      router.push('/');
    } catch (error) {
      console.error('Failed to save workout:', error);
      alert('Failed to save workout. Please try again.');
    } finally {
      setIsLoading(false);
    }
  };

  const totalWorkoutTime = formatTime(formData.totalMinutes, formData.totalSeconds);
  const totalRoundTime = formData.rounds.reduce((total, round) => {
    return total + (round.minutes * 60) + round.seconds;
  }, 0);

  return (
    <div className="max-w-4xl mx-auto space-y-6">
      {/* Header */}
      <div className="text-center space-y-2">
        <h1 className="text-4xl font-bold text-white">Log Workout</h1>
        <p className="text-white/80">Manually add a completed 100-swing session</p>
      </div>

      <form onSubmit={handleSubmit} className="space-y-6">
        {/* Basic Workout Info */}
        <Card className="glass border-white/20">
          <CardHeader>
            <CardTitle className="text-white flex items-center gap-2">
              <Plus className="w-5 h-5" />
              Workout Details
            </CardTitle>
          </CardHeader>
          <CardContent className="space-y-4">
            <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
              <div className="space-y-2">
                <Label htmlFor="date" className="text-white">Date</Label>
                <Input
                  id="date"
                  type="date"
                  value={formData.date}
                  onChange={(e) => updateFormData('date', e.target.value)}
                  className="bg-white/10 border-white/20 text-white"
                  required
                />
              </div>

              <div className="space-y-2">
                <Label htmlFor="exercise" className="text-white">Strength Exercise</Label>
                <Select
                  value={formData.strengthExercise}
                  onValueChange={(value: StrengthExercise) => updateFormData('strengthExercise', value)}
                >
                  <SelectTrigger className="bg-white/10 border-white/20 text-white">
                    <SelectValue />
                  </SelectTrigger>
                  <SelectContent>
                    {STRENGTH_EXERCISES.map((exercise) => (
                      <SelectItem key={exercise} value={exercise}>
                        {exercise}
                      </SelectItem>
                    ))}
                  </SelectContent>
                </Select>
              </div>

              <div className="space-y-2">
                <Label htmlFor="weight" className="text-white">Kettlebell Weight</Label>
                <Select
                  value={formData.kettlebellWeight.toString()}
                  onValueChange={(value) => updateFormData('kettlebellWeight', parseInt(value))}
                >
                  <SelectTrigger className="bg-white/10 border-white/20 text-white">
                    <SelectValue />
                  </SelectTrigger>
                  <SelectContent>
                    {KETTLEBELL_WEIGHTS.map((weight) => (
                      <SelectItem key={weight} value={weight.toString()}>
                        {weight}kg
                      </SelectItem>
                    ))}
                  </SelectContent>
                </Select>
              </div>

              <div className="space-y-2">
                <Label className="text-white">Total Workout Time</Label>
                <div className="flex gap-2">
                  <div className="flex-1">
                    <Input
                      type="number"
                      placeholder="Minutes"
                      value={formData.totalMinutes || ''}
                      onChange={(e) => updateFormData('totalMinutes', parseInt(e.target.value) || 0)}
                      className="bg-white/10 border-white/20 text-white"
                      min="0"
                      max="120"
                    />
                  </div>
                  <div className="flex-1">
                    <Input
                      type="number"
                      placeholder="Seconds"
                      value={formData.totalSeconds || ''}
                      onChange={(e) => updateFormData('totalSeconds', parseInt(e.target.value) || 0)}
                      className="bg-white/10 border-white/20 text-white"
                      min="0"
                      max="59"
                    />
                  </div>
                </div>
                <div className="text-center">
                  <span className="text-white/80 text-sm">Total: {totalWorkoutTime}</span>
                </div>
              </div>
            </div>

            <div className="space-y-2">
              <Label htmlFor="notes" className="text-white">Notes (Optional)</Label>
              <Input
                id="notes"
                placeholder="Any additional notes about this workout..."
                value={formData.notes}
                onChange={(e) => updateFormData('notes', e.target.value)}
                className="bg-white/10 border-white/20 text-white"
              />
            </div>
          </CardContent>
        </Card>

        {/* Round Times */}
        <Card className="glass border-white/20">
          <CardHeader>
            <CardTitle className="text-white flex items-center gap-2">
              <Clock className="w-5 h-5" />
              Round Times
            </CardTitle>
            <div className="flex gap-2">
              <Button
                type="button"
                onClick={estimateRoundTimes}
                variant="outline"
                size="sm"
                className="border-white/40 text-white bg-black/20 hover:bg-black/40"
              >
                <Calculator className="w-4 h-4 mr-2" />
                Auto-Estimate
              </Button>
              <Button
                type="button"
                onClick={calculateTotalFromRounds}
                variant="outline"
                size="sm"
                className="border-white/40 text-white bg-black/20 hover:bg-black/40"
              >
                <Plus className="w-4 h-4 mr-2" />
                Calculate Total
              </Button>
            </div>
          </CardHeader>
          <CardContent className="space-y-4">
            <div className="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-4 gap-4">
              {formData.rounds.map((round, index) => (
                <div key={round.roundNumber} className="space-y-2">
                  <Label className="text-white font-medium">Round {round.roundNumber}</Label>
                  <div className="space-y-2">
                    <Input
                      type="number"
                      placeholder="Min"
                      value={round.minutes || ''}
                      onChange={(e) => updateRoundTime(index, 'minutes', parseInt(e.target.value) || 0)}
                      className="bg-white/10 border-white/20 text-white text-center"
                      min="0"
                      max="30"
                    />
                    <Input
                      type="number"
                      placeholder="Sec"
                      value={round.seconds || ''}
                      onChange={(e) => updateRoundTime(index, 'seconds', parseInt(e.target.value) || 0)}
                      className="bg-white/10 border-white/20 text-white text-center"
                      min="0"
                      max="59"
                    />
                    <div className="text-center text-white/70 text-sm">
                      {formatTime(round.minutes, round.seconds)}
                    </div>
                  </div>
                </div>
              ))}
            </div>

            <div className="text-center p-4 border border-white/20 rounded-lg">
              <div className="text-white/80 text-sm">Sum of all rounds:</div>
              <div className="text-white font-semibold">
                {formatTime(Math.floor(totalRoundTime / 60), totalRoundTime % 60)}
              </div>
              {totalRoundTime !== (formData.totalMinutes * 60 + formData.totalSeconds) && (
                <div className="text-yellow-400 text-xs mt-1">
                  ⚠️ Round times don&apos;t match total workout time
                </div>
              )}
            </div>
          </CardContent>
        </Card>

        {/* Workout Summary */}
        <Card className="glass border-white/20">
          <CardHeader>
            <CardTitle className="text-white">Workout Summary</CardTitle>
          </CardHeader>
          <CardContent>
            <div className="grid grid-cols-2 md:grid-cols-4 gap-4 text-center">
              <div>
                <div className="text-2xl font-bold text-white">100</div>
                <div className="text-white/60">Total Swings</div>
              </div>
              <div>
                <div className="text-2xl font-bold text-white">{formData.kettlebellWeight}kg</div>
                <div className="text-white/60">Weight</div>
              </div>
              <div>
                <div className="text-2xl font-bold text-white">{totalWorkoutTime}</div>
                <div className="text-white/60">Duration</div>
              </div>
              <div>
                <div className="text-2xl font-bold text-white">{formData.strengthExercise}</div>
                <div className="text-white/60">Exercise</div>
              </div>
            </div>
          </CardContent>
        </Card>

        {/* Submit Button */}
        <div className="flex gap-4">
          <Button
            type="submit"
            disabled={!validateForm() || isLoading}
            className="flex-1 bg-gradient-to-r from-green-400 to-emerald-500 hover:from-green-500 hover:to-emerald-600 disabled:opacity-50 py-3"
          >
            <Save className="w-5 h-5 mr-2" />
            {isLoading ? 'Saving...' : 'Save Workout'}
          </Button>
          
          <Button
            type="button"
            onClick={() => router.push('/')}
            variant="outline"
            className="border-white/40 text-white bg-black/20 hover:bg-black/40 px-8"
          >
            Cancel
          </Button>
        </div>
      </form>
    </div>
  );
}